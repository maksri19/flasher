Renderer renderer_create(Context* ctx) {
	// creating renderer object
	Renderer this = {0};
	this.w = ctx->w;
	this.h = ctx->h;

	// load opengl function
	if (!gladLoadGLLoader((GLADloadproc)glfwGetProcAddress)) log_exit("Failed to initialize GLAD\n");

	// create glad textures and fbo
	glGenTextures(1, &this.glad_texture);
	glBindTexture(GL_TEXTURE_2D, this.glad_texture);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
	glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, this.w, this.h, 0, GL_RGBA, 0x8035, NULL);

	// attach texture to READ FBO
	glGenFramebuffers(1, &this.glad_fbo);
	glBindFramebuffer(GL_READ_FRAMEBUFFER, this.glad_fbo);
	glFramebufferTexture2D(GL_READ_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, this.glad_texture, 0);

	// allocate buffer for renderer
	size_t total_px = this.w * this.h;
	this.buffer = memory_alloc(sizeof(RGBA) * total_px);
	memset(this.buffer, 0, sizeof(RGBA) * total_px);
	
	return this;
}


void renderer_present(Renderer* this) {
	// update buffer into gpu texture
	glBindTexture(GL_TEXTURE_2D, this->glad_texture);
	glTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, this->w, this->h, GL_RGBA, 0x8035, this->buffer);
	
	// blit FBO texture to glfw window
	glBindFramebuffer(GL_READ_FRAMEBUFFER, this->glad_fbo);
	glBindFramebuffer(GL_DRAW_FRAMEBUFFER, 0);
	glBlitFramebuffer(0, this->h, this->w, 0, 0, 0, this->w, this->h, GL_COLOR_BUFFER_BIT, GL_NEAREST);
}


void renderer_clear(Renderer* this, RGBA color) {
	// set every pixel with color
	size_t total_px = this->w * this->h;
	for (size_t i = 0; i < total_px; i++) {
		this->buffer[i] = color;
	}
}


void renderer_fillRect(Renderer* this, int x, int y, int w, int h, RGBA color) {
	// set pixel in range with color
	for (int dx = 0; dx < w; dx++) {
		for (int dy = 0; dy < h; dy++) {
			int cx = x + dx;
			int cy = y + dy;
			if (cx >= 0 && cx < this->w && cy >= 0 && cy < this->h) {
				this->buffer[cy * this->w + cx] = color;
			}
		}
	}
}


void renderer_drawLine(Renderer* this, int x0, int y0, int x1, int y1, RGBA color, int thickness) {
	// normalize coordinate off with thickness
	x0 -= thickness/2;
	x1 -= thickness/2;
	y0 -= thickness/2;
	y1 -= thickness/2;

	// setup parameter
	int dx = abs(x1 - x0);
	int dy = abs(y1 - y0);
	int sx = (x0 < x1) ? 1 : -1;
	int sy = (y0 < y1) ? 1 : -1;
	int err = dx - dy;

	while (true) {
		// paint a box size of thickness
		for (int i = 0; i < thickness; i++) {
			for (int j = 0; j < thickness; j++) {
				int nx0 = (x0+j), ny0 = (y0+i);
				if (nx0 >= 0 && nx0 < this->w && ny0 >= 0 && ny0 < this->h)
					this->buffer[ny0 * this->w + nx0] = color;
			}
		}
		
		// adjust for correct trajectory
		if (x0 == x1 && y0 == y1) break;
		int e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x0 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y0 += sy;
        }
	}
}


void renderer_drawChar(Renderer* this, char ch, int x, int y, double scale, RGBA color) {
	// questionmark unknown character
	if (ch < 32 || ch > 126) ch = '?';


	// iterate across 8x8 character data
	const uint8_t* glyph = fontbasic8x8[ch-32];
	for (int r = 0; r < 8; r++) {
		for (int c = 0; c < 8; c++) {
			if ((glyph[r] >> (7-c)) & 1) {
				int start_x = (double)x + c*scale;
				int start_y = (double)y + r*scale;
				
				// paint box size of scale
				for (int sy = 0; sy < (int)round(scale); sy++) {
					for (int sx = 0; sx < (int)round(scale); sx++) {
						int px = start_x + sx;	
						int py = start_y + sy;
						if (px >= 0 && px < this->w && py >= 0 && py < this->h) this->buffer[py * this->w + px] = color;
					}
				}
			}
		}
	}
}
